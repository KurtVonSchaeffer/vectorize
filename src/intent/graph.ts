// Recreation mode (prototype, docs/design-intent.md): an object graph built from SAM regions named
// by a vision model, and the SVG constructed from the graph as a designer would build it by hand:
// one solid shape per object, children punched out of their parent (no overlaps, even-odd holes),
// mirrored pairs as true mirror images, each object's colour taken from its own pixels only.
import { traceLabels, type LabelMap, type TraceOptions } from '../trace'
import { mirrorAxis } from './primitives'
import type { ObjectMask } from './sam'
import { traceWhere } from './semantic'

export type StyleKind = 'shadow' | 'highlight' | 'fur' | 'engraving'
const STYLE_MAX: Record<StyleKind, number> = { shadow: 3, highlight: 3, fur: 8, engraving: 10 }
const STYLE_TONE: Record<StyleKind, 'dark' | 'light' | 'base'> = { shadow: 'dark', highlight: 'light', fur: 'dark', engraving: 'dark' }

/**
 * Why a feature is there (schema v3). Identity features make the mascot recognisable (an eye mask,
 * a jaw) and are never dropped; structure shapes the form (a cheek, a forehead shadow); style is the
 * artist's rendering (shading); decorative is texture (fur clumps, engraving), dropped first.
 */
export type FeatureRole = 'signature' | 'identity' | 'structure' | 'style' | 'decorative'
/** Signature (schema v4): without it, it's a different character (the eye mask, the brow). */
const ROLE_IMPORTANCE: Record<FeatureRole, number> = { signature: 10, identity: 9, structure: 7, style: 5, decorative: 3 }
const KEPT_ALWAYS: FeatureRole[] = ['signature', 'identity']
const KIND_ROLE: Record<StyleKind, FeatureRole> = { shadow: 'style', highlight: 'style', fur: 'decorative', engraving: 'decorative' }

/** A visual feature of a part: what to look for, why it matters, and how to draw it. */
export interface FeatureSpec {
  kind: StyleKind
  /** e.g. "eye-mask"; pieces are named `<part>-<name>-<n>` (default: the kind). */
  name?: string
  role?: FeatureRole
  /** 0–10; default from the role (identity 10, structure 7, style 5, decorative 3). */
  importance?: number
  /** At most this many pieces (default by kind). */
  max?: number
  /**
   * 'stroke': drawn as centrelines with a width (engraving, wrinkles, outlines), one path per
   * feature. 'procedural' (schema v6; 'texture' is the same): not traced but regenerated by a
   * `generator`, one compound path. The fur generator draws tapered strands following the
   * artwork's own stroke direction, seeded where it has strands of this tone.
   */
  render?: 'fill' | 'stroke' | 'procedural' | 'texture'
  /** For 'procedural': which generator (only 'fur' so far; hair, grass, grain and feathers would join it). */
  generator?: 'fur'
  /** Generator settings: strands per 100 px² (default 1.2), length and base width in px (14, 2.4), tone. */
  texture?: { density?: number; length?: number; width?: number; tone?: 'light' | 'dark' }
}

const isProcedural = (s: FeatureSpec) => s.render === 'procedural' || s.render === 'texture'

/** What the vision step returns: the parts it sees, which numbered regions make each, and how. */
export interface Labels {
  /**
   * The most paths the illustration may have (schema v3). Parts always stay; features are dropped
   * least important first (part importance × feature importance × the piece's own strength) until
   * the count fits. Identity features always stay. Unset: no limit.
   */
  budget?: number
  parts: {
    /** How much the part matters to recognising the artwork, 0–10 (default 5). */
    importance?: number
    /**
     * The most paths this part's own features may take (schema v4), on top of the overall budget:
     * geometry is spent where recognition is (the face 15, the hands 5). Signature and identity
     * features don't count against it and always stay.
     */
    pathBudget?: number
    /** Visual features (schema v3); `styles` (v2) are read as features with their kind's role. */
    features?: FeatureSpec[]
    /** e.g. "gorilla", "head", "face", "left_eye". */
    name: string
    parent: string | null
    /** Region numbers (indices into the SAM regions) that together make the part… */
    regions?: number[]
    /**
     * …or points on the part (image px), for SAM to segment from: a vision model can point at an
     * eye that SAM's automatic grid never isolated. `pick` chooses among SAM's three masks.
     */
    points?: [number, number][]
    pick?: 'small' | 'large' | 'best'
    /**
     * …or a box around the part (image px: x0, y0, x1, y1): the part is the pixels of its tone in
     * the box (dark: the darkest 40%, light: the lightest 50%, base: all), smoothed, its larger
     * pieces kept. On engraved art SAM can't cut an eye out of the hatching from a point; a box
     * from the vision step can.
     */
    box?: [number, number, number, number]
    /**
     * Style regions inside the part (schema v2): how the artist rendered it, not what it is.
     * Each kind is found in the part's own pixels and becomes named child shapes, at most `max`
     * of them, largest and strongest first:
     * - shadow: large dark masses (the lightness blurred over a few % of the part);
     * - highlight: large light masses;
     * - fur: clumps, darker than their surroundings at a medium scale;
     * - engraving: near-black line work at full detail.
     */
    styles?: { kind: StyleKind; max?: number }[]
    /** Colour hint: the part's dark tone, light tone, or its base (default). */
    tone?: 'dark' | 'light' | 'base'
    /** Draw as the mirror image of this part (across the nearest symmetric ancestor). */
    mirrorOf?: string
  }[]
}

export interface GraphNode {
  name: string
  parent: number
  children: number[]
  mask: Uint8Array
  area: number
  box: [number, number, number, number]
  tone: 'dark' | 'light' | 'base'
  mirrorOf: number
  importance: number
  pathBudget: number
  features: FeatureSpec[]
  /** A feature piece of its parent (made during construction). */
  style?: StyleKind
  role?: FeatureRole
  /** Drawn as a stroke: centreline path data and width (made during construction). */
  stroke?: { d: string; width: number }
  /** Synthesized texture: filled path data of regenerated strands (made during construction). */
  synth?: string
}

export interface Graph {
  nodes: GraphNode[]
  roots: number[]
  w: number
  h: number
  budget: number
}

/** Each part as the union of its regions, smoothed (a designer's shape, not the cut's jaggies). */
export function buildGraph(regions: ObjectMask[], labels: Labels, src: ImageData): Graph {
  const { width: w, height: h } = src
  const n = w * h
  const index = new Map(labels.parts.map((p, i) => [p.name, i]))
  const lum = (p: number) => 0.299 * src.data[p * 4] + 0.587 * src.data[p * 4 + 1] + 0.114 * src.data[p * 4 + 2]
  const nodes: GraphNode[] = labels.parts.map((p) => {
    const raw = new Uint8Array(n)
    for (const r of p.regions ?? []) {
      const m = regions[r]
      if (!m) continue
      for (let y = m.box[1]; y <= m.box[3]; y++) for (let x = m.box[0]; x <= m.box[2]; x++) if (m.mask[y * w + x]) raw[y * w + x] = 1
    }
    if (p.box) {
      const [x0, y0, x1, y1] = p.box.map((v) => Math.round(v))
      const inBox: number[] = []
      for (let y = Math.max(0, y0); y <= Math.min(h - 1, y1); y++) for (let x = Math.max(0, x0); x <= Math.min(w - 1, x1); x++) inBox.push(y * w + x)
      const sorted = inBox.map(lum).sort((a, b) => a - b)
      const tone = p.tone ?? 'base'
      const cut = tone === 'dark' ? sorted[Math.floor(sorted.length * 0.4)] : sorted[Math.floor(sorted.length * 0.5)]
      const pick = new Uint8Array(n)
      for (const q of inBox) if (tone === 'base' || (tone === 'dark' ? lum(q) <= cut : lum(q) >= cut)) pick[q] = 1
      // Smooth the hatching into a shape, then keep the pieces at least a fifth of the largest.
      const sm = smoothMask(pick, w, h, 2)
      for (const piece of largePieces(sm, w, h, 0.2)) raw[piece] = 1
    }
    const mask = smoothMask(raw, w, h, 1.5)
    return {
      name: p.name,
      parent: p.parent ? (index.get(p.parent) ?? -1) : -1,
      children: [],
      mask,
      ...measure(mask, w, h),
      tone: p.tone ?? 'base',
      mirrorOf: p.mirrorOf ? (index.get(p.mirrorOf) ?? -1) : -1,
      importance: p.importance ?? 5,
      pathBudget: p.pathBudget ?? Infinity,
      features: [...(p.features ?? []), ...(p.styles ?? []).map((s) => ({ kind: s.kind, max: s.max }))],
    }
  })
  nodes.forEach((nd, i) => nd.parent >= 0 && nodes[nd.parent].children.push(i))
  return { nodes, roots: nodes.map((_, i) => i).filter((i) => nodes[i].parent < 0), w, h, budget: labels.budget ?? Infinity }
}

export interface Recreation {
  svg: string
  objects: number
  /** Paths written for the illustration (one per object). */
  paths: number
  /** The graph as an indented list, with colours and areas. */
  tree: string
}

/**
 * The SVG from the graph. The artwork outside the texture is the flat trace (knockout, with a hole
 * where an object is). Inside, every pixel belongs to the deepest object holding it; each
 * object is traced from its own pixels, so its children are holes in it (even-odd) and nothing is
 * drawn twice. The root reaches 1 px under the artwork.
 */
export function recreate(map: LabelMap, graph: Graph, src: ImageData, trace: TraceOptions): Recreation {
  const { w, h, nodes } = graph
  const n = w * h
  // Depth-first order (parents before children).
  const order: number[] = []
  const visit = (i: number) => (order.push(i), nodes[i].children.forEach(visit))
  graph.roots.forEach(visit)
  // Ownership: deepest node wins, drawn in order.
  const own = new Int32Array(n).fill(-1)
  for (const i of order) {
    if (nodes[i].mirrorOf >= 0) continue
    const m = nodes[i].mask
    for (let p = 0; p < n; p++) if (m[p]) own[p] = i
  }
  // Mirrored nodes: the partner's pixels reflected across the nearest symmetric ancestor's axis.
  for (const i of order) {
    const nd = nodes[i]
    if (nd.mirrorOf < 0) continue
    let a = nd.parent
    let axis: number | null = null
    while (a >= 0 && axis === null) {
      const s = mirrorAxis({ mask: nodes[a].mask, area: nodes[a].area, box: nodes[a].box, score: 1, point: [0, 0] }, w)
      if (s.score >= 0.8) axis = s.axis
      a = nodes[a].parent
    }
    if (axis === null) axis = (nodes[nd.mirrorOf].box[0] + nodes[nd.mirrorOf].box[2] + nd.box[0] + nd.box[2]) / 4
    const a2 = Math.round(axis * 2)
    // Clear the node's own pixels (they go to its parent), then mirror the partner in.
    for (let p = 0; p < n; p++) if (own[p] === i) own[p] = nd.parent
    const src2 = nodes[nd.mirrorOf]
    for (let y = src2.box[1]; y <= src2.box[3]; y++)
      for (let x = src2.box[0]; x <= src2.box[2]; x++) {
        if (!src2.mask[y * w + x]) continue
        const mx = a2 - x
        if (mx >= 0 && mx < w) own[y * w + mx] = i
      }
  }
  // Texture no object holds (the green behind the shoulders, the ring under an arm) is left to the
  // artwork tracer: it belongs to the logo, not to the illustration.
  const root = graph.roots.slice().sort((a, b) => nodes[b].area - nodes[a].area)[0] ?? -1

  // Visual features (schema v3): found in each part's own pixels, cut to the path budget (least
  // important first, identity never), then added as the part's children: fills own their pixels,
  // strokes are drawn over them.
  const candidates = findFeatures(nodes, order, own, src, w, h)
  const partPaths = order.filter((i) => own.some((o) => o === i)).length
  const kept = selectFeatures(candidates, partPaths, graph.budget, nodes)
  applyFeatures(nodes, kept, own, src, w, h)

  // Colours from each object's own pixels only (a stroke: the pixels it was drawn from).
  const colour = nodes.map((nd, i) => {
    const l: number[] = []
    const px: number[] = []
    if (nd.stroke || nd.synth) for (let p = 0; p < n; p++) nd.mask[p] && px.push(p)
    else for (let p = 0; p < n; p++) if (own[p] === i) px.push(p)
    if (!px.length) return 0
    for (const p of px) l.push(0.299 * src.data[p * 4] + 0.587 * src.data[p * 4 + 1] + 0.114 * src.data[p * 4 + 2])
    const sorted = l.slice().sort((a, b) => a - b)
    const pick = (lo: number, hi: number) => {
      const a = sorted[Math.floor(lo * (sorted.length - 1))], b = sorted[Math.floor(hi * (sorted.length - 1))]
      let r = 0, g = 0, bl = 0, c = 0
      px.forEach((p, k) => {
        if (l[k] < a || l[k] > b) return
        r += src.data[p * 4]; g += src.data[p * 4 + 1]; bl += src.data[p * 4 + 2]; c++
      })
      return c ? (Math.round(r / c) << 16) | (Math.round(g / c) << 8) | Math.round(bl / c) : 0
    }
    // Dark parts (eyes, nostrils): their darkest third. Light parts: their lightest half. Bases:
    // the band around the 60th percentile, the tone engraved fur is seen as.
    // Synthesized strands take the part's brightest (or darkest) strokes, as the artist's pen did.
    if (nd.synth) return nd.tone === 'dark' ? pick(0, 0.15) : pick(0.85, 1)
    return nd.tone === 'dark' ? pick(0, 0.33) : nd.tone === 'light' ? pick(0.5, 1) : pick(0.45, 0.8)
  })
  // Mirrored pairs share a colour.
  nodes.forEach((nd, i) => nd.mirrorOf >= 0 && (colour[i] = colour[nd.mirrorOf]))

  // The artwork around the illustration, with a hole where an object is.
  const flat: LabelMap = { ...map, labels: map.labels.map((l, p) => (own[p] >= 0 ? 254 : l)), fine: undefined }
  const flatBody = traceLabels(flat, { ...trace, mode: 'knockout', spread: 0 })
    .svg.replace(/^[\s\S]*?<svg\b[^>]*>/i, '')
    .replace(/<\/svg>\s*$/i, '')
  // The illustration, nested as the graph.
  let paths = 0
  const hex = (c: number) => `#${c.toString(16).padStart(6, '0').toUpperCase()}`
  // The root reaches 1 px past the illustration, under the artwork, so no seam shows between them.
  const any = (p: number) => own[p] >= 0
  const near = (p: number) => any(p) || (p % w > 0 && any(p - 1)) || (p % w < w - 1 && any(p + 1)) || (p >= w && any(p - w)) || (p < n - w && any(p + w))
  const emit = (i: number): string => {
    const nd = nodes[i]
    const role = nd.role ? ` data-role="${nd.role}"` : ''
    if (nd.synth) {
      paths++
      return `<path id="${nd.name}"${role} d="${nd.synth}" fill="${hex(colour[i])}"/>`
    }
    if (nd.stroke) {
      paths++
      return `<path id="${nd.name}"${role} d="${nd.stroke.d}" fill="none" stroke="${hex(colour[i])}" stroke-width="${nd.stroke.width}" stroke-linecap="round" stroke-linejoin="round"/>`
    }
    const at = i === root ? (p: number) => own[p] === i || (own[p] < 0 && near(p)) : (p: number) => own[p] === i
    const d = traceWhere(at, w, h, trace)
    const self = d ? (paths++, `<path id="${nd.name}"${role} d="${d}" fill="${hex(colour[i])}" fill-rule="evenodd"/>`) : ''
    // Fills first, then textures, then strokes over them.
    const rank = (c: number) => (nodes[c].stroke ? 2 : nodes[c].synth ? 1 : 0)
    const kids = nd.children.slice().sort((a, b) => rank(a) - rank(b)).map(emit).join('')
    return nd.children.length ? `<g id="${nd.name}-group">${self}${kids}</g>` : self
  }
  const body = graph.roots.map(emit).join('')
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><g id="artwork">${flatBody}</g><g id="illustration">${body}</g></svg>`
  const lines: string[] = []
  const list = (i: number, depth: number) => {
    let a = 0
    for (let p = 0; p < n; p++) if (own[p] === i) a++
    const nd = nodes[i]
    const how = nd.stroke ? `stroke ${nd.stroke.width}px` : `${a} px`
    lines.push(`${'  '.repeat(depth)}${nd.name}  ${hex(colour[i])}  ${how}${nd.role ? `  [${nd.role}]` : ''}${nd.mirrorOf >= 0 ? `  (mirror of ${nodes[nd.mirrorOf].name})` : ''}`)
    nodes[i].children.forEach((c) => list(c, depth + 1))
  }
  graph.roots.forEach((r) => list(r, 0))
  return { svg, objects: nodes.length, paths, tree: lines.join('\n') }
}

interface Candidate {
  part: number
  spec: FeatureSpec
  role: FeatureRole
  /** Rank within its feature (0 = strongest). */
  rank: number
  pixels: number[]
  /** Part importance × feature importance × the piece's strength relative to the feature's strongest. */
  priority: number
}

/**
 * The feature pieces of every part that asks for them. Each kind is measured against the part's
 * base lightness (its 45th–80th percentile band): shadow and highlight on the lightness blurred over
 * ~4% of the part's size, fur on the difference between a fine (2 px) and a coarse (8 px) blur,
 * engraving on near-black pixels at full detail. Pieces under 0.3% of the part (and 20 px) are
 * dropped; the largest × strongest `max` are candidates.
 */
function findFeatures(nodes: GraphNode[], order: number[], own: Int32Array, src: ImageData, w: number, h: number): Candidate[] {
  const n = w * h
  const lum = new Float32Array(n)
  for (let p = 0; p < n; p++) lum[p] = 0.299 * src.data[p * 4] + 0.587 * src.data[p * 4 + 1] + 0.114 * src.data[p * 4 + 2]
  const contrast = 28
  const out: Candidate[] = []
  for (const i of order) {
    const nd = nodes[i]
    if (!nd.features.length) continue
    const px: number[] = []
    for (let p = 0; p < n; p++) if (own[p] === i) px.push(p)
    if (!px.length) continue
    const ls = px.map((p) => lum[p]).sort((a, b) => a - b)
    const lo = ls[Math.floor(ls.length * 0.45)], hi = ls[Math.floor(ls.length * 0.8)]
    let base = 0, c = 0
    for (const v of ls) if (v >= lo && v <= hi) (base += v), c++
    base /= Math.max(1, c)
    const inPart = new Uint8Array(n)
    for (const p of px) inPart[p] = 1
    const sigma = Math.max(3, Math.round(Math.sqrt(px.length) * 0.04))
    const coarse = blurField(lum, w, h, sigma)
    const fine2 = blurField(lum, w, h, 2)
    const wide = blurField(lum, w, h, 8)
    const minArea = Math.max(20, Math.round(px.length * 0.003))
    // In order: darker kinds first, highlights last, so a highlight inside a shadow shows.
    const specs = nd.features.slice().sort((a, b) => ['shadow', 'fur', 'engraving', 'highlight'].indexOf(a.kind) - ['shadow', 'fur', 'engraving', 'highlight'].indexOf(b.kind))
    for (const spec of specs) {
      const { kind, max } = spec
      if (isProcedural(spec)) {
        // Regenerated, not traced: one candidate covering the part, one path.
        const role = spec.role ?? KIND_ROLE[kind]
        out.push({ part: i, spec, role, rank: 0, pixels: px.slice(), priority: (nd.importance / 10) * ((spec.importance ?? ROLE_IMPORTANCE[role]) / 10) })
        continue
      }
      const sel = new Uint8Array(n)
      for (const p of px) {
        if (kind === 'shadow') sel[p] = coarse[p] < base - contrast ? 1 : 0
        else if (kind === 'highlight') sel[p] = coarse[p] > base + contrast ? 1 : 0
        else if (kind === 'fur') sel[p] = fine2[p] < wide[p] - contrast / 2 ? 1 : 0
        else sel[p] = lum[p] < 45 ? 1 : 0
      }
      // Strokes keep their strands thin: smoothing would merge them into blobs.
      const shaped = kind === 'engraving' || spec.render === 'stroke' ? sel : smoothMask(sel, w, h, 1.5)
      const pieces = piecesOf(shaped, inPart, w)
        .filter((pc) => pc.length >= minArea)
        .map((pc) => ({ pc, score: pc.length * Math.abs(pc.reduce((s, p) => s + lum[p], 0) / pc.length - base) }))
        .sort((a, b) => b.score - a.score)
        .slice(0, max ?? STYLE_MAX[kind])
      const role = spec.role ?? KIND_ROLE[kind]
      const importance = spec.importance ?? ROLE_IMPORTANCE[role]
      const top = pieces[0]?.score ?? 1
      pieces.forEach(({ pc, score }, rank) => out.push({ part: i, spec, role, rank, pixels: pc, priority: (nd.importance / 10) * (importance / 10) * (score / top) }))
    }
  }
  return out
}

/**
 * The candidates that fit the path budget. Parts take `partPaths`; each fill piece is one path, and
 * a stroked feature is one path however many pieces it has. Identity features always stay; the rest
 * are taken in priority order while they fit.
 */
function selectFeatures(candidates: Candidate[], partPaths: number, budget: number, nodes: GraphNode[]): Candidate[] {
  const kept: Candidate[] = []
  const strokeGroups = new Set<string>()
  const perPart = new Map<number, number>()
  let used = partPaths
  const group = (c: Candidate) => `${c.part}|${c.spec.name ?? c.spec.kind}`
  // A stroked feature is one path however many pieces; a procedural feature is one; a fill piece is one.
  const cost = (c: Candidate) => (c.spec.render === 'stroke' ? (strokeGroups.has(group(c)) ? 0 : 1) : 1)
  const take = (c: Candidate, counts: boolean) => {
    const k = cost(c)
    used += k
    if (counts) perPart.set(c.part, (perPart.get(c.part) ?? 0) + k)
    if (c.spec.render === 'stroke') strokeGroups.add(group(c))
    kept.push(c)
  }
  for (const c of candidates) if (KEPT_ALWAYS.includes(c.role)) take(c, false)
  for (const c of candidates.filter((x) => !KEPT_ALWAYS.includes(x.role)).sort((a, b) => b.priority - a.priority)) {
    const k = cost(c)
    if (used + k > budget || (perPart.get(c.part) ?? 0) + k > nodes[c.part].pathBudget) continue
    take(c, true)
  }
  return kept
}

/**
 * Kept candidates as nodes: fills own their pixels; each stroked feature is one centreline path;
 * each texture is one compound path of synthesized strands.
 */
function applyFeatures(nodes: GraphNode[], kept: Candidate[], own: Int32Array, src: ImageData, w: number, h: number) {
  const n = w * h
  // Textures: strands regenerated over the part.
  for (const c of kept.filter((x) => isProcedural(x.spec))) {
    const mask = new Uint8Array(n)
    for (const p of c.pixels) mask[p] = 1
    const tone = c.spec.texture?.tone ?? 'light'
    const d = synthesizeStrands(mask, src, w, h, { ...c.spec.texture, tone })
    if (!d) continue
    const id = nodes.push({ name: `${nodes[c.part].name}-${c.spec.name ?? c.spec.kind}`, parent: c.part, children: [], mask, ...measure(mask, w, h), tone, mirrorOf: -1, importance: 0, pathBudget: Infinity, features: [], style: c.spec.kind, role: c.role, synth: d }) - 1
    nodes[c.part].children.push(id)
  }
  // Fills: parts in drawing order, darker kinds first within a part, so highlights land on top.
  const kindOrder = ['shadow', 'fur', 'engraving', 'highlight']
  const fills = kept
    .filter((c) => c.spec.render !== 'stroke' && !isProcedural(c.spec))
    .sort((a, b) => a.part - b.part || kindOrder.indexOf(a.spec.kind) - kindOrder.indexOf(b.spec.kind) || a.rank - b.rank)
  const counts = new Map<string, number>()
  for (const c of fills) {
    const nd = nodes[c.part]
    const base = `${nd.name}-${c.spec.name ?? c.spec.kind}`
    const k = (counts.get(base) ?? 0) + 1
    counts.set(base, k)
    const mask = new Uint8Array(n)
    for (const p of c.pixels) mask[p] = 1
    const id = nodes.push({ name: `${base}-${k}`, parent: c.part, children: [], mask, ...measure(mask, w, h), tone: STYLE_TONE[c.spec.kind], mirrorOf: -1, importance: 0, pathBudget: Infinity, features: [], style: c.spec.kind, role: c.role }) - 1
    nodes[c.part].children.push(id)
    for (const p of c.pixels) own[p] = id
  }
  // Strokes: all pieces of one feature together, thinned to centrelines, one path.
  const groups = new Map<string, Candidate[]>()
  for (const c of kept.filter((x) => x.spec.render === 'stroke')) {
    const key = `${c.part}|${c.spec.name ?? c.spec.kind}`
    groups.set(key, [...(groups.get(key) ?? []), c])
  }
  for (const list of groups.values()) {
    const c0 = list[0]
    const mask = new Uint8Array(n)
    // Each piece is judged on its own: only line-shaped ones join the stroke.
    for (const c of list) {
      const one = new Uint8Array(n)
      for (const p of c.pixels) one[p] = 1
      if (centrelines(one, w, h)) for (const p of c.pixels) mask[p] = 1
    }
    const stroke = centrelines(mask, w, h)
    if (!stroke) continue
    const id = nodes.push({ name: `${nodes[c0.part].name}-${c0.spec.name ?? c0.spec.kind}`, parent: c0.part, children: [], mask, ...measure(mask, w, h), tone: 'dark', mirrorOf: -1, importance: 0, pathBudget: Infinity, features: [], style: c0.spec.kind, role: c0.role, stroke }) - 1
    nodes[c0.part].children.push(id)
  }
}

/**
 * A mask's line work as stroked centrelines: thinned to 1 px (Zhang–Suen), followed from end to
 * end (and around loops) into polylines, simplified (Douglas–Peucker, 0.7 px), with one width for
 * the whole set: area ÷ centreline length, between 0.8 and 6 px.
 */
function centrelines(mask: Uint8Array, w: number, h: number): { d: string; width: number } | null {
  const { box } = measure(mask, w, h)
  const [x0, y0, x1, y1] = [Math.max(0, box[0] - 1), Math.max(0, box[1] - 1), Math.min(w - 1, box[2] + 1), Math.min(h - 1, box[3] + 1)]
  const cw = x1 - x0 + 1, ch = y1 - y0 + 1
  const m = new Uint8Array(cw * ch)
  let area = 0
  for (let y = 0; y < ch; y++) for (let x = 0; x < cw; x++) if (mask[(y + y0) * w + x + x0]) (m[y * cw + x] = 1), area++
  if (!area) return null
  thin(m, cw, ch)
  const at = (x: number, y: number) => x >= 0 && y >= 0 && x < cw && y < ch && m[y * cw + x] === 1
  const nbrs = (x: number, y: number) => {
    const out: [number, number][] = []
    for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) if ((dx || dy) && at(x + dx, y + dy)) out.push([x + dx, y + dy])
    return out
  }
  const used = new Set<number>()
  const lines: [number, number][][] = []
  let length = 0
  const walk = (sx: number, sy: number) => {
    const line: [number, number][] = [[sx, sy]]
    used.add(sy * cw + sx)
    let [x, y] = [sx, sy]
    for (;;) {
      const next = nbrs(x, y).find(([nx, ny]) => !used.has(ny * cw + nx))
      if (!next) break
      length += Math.hypot(next[0] - x, next[1] - y)
      ;[x, y] = next
      used.add(y * cw + x)
      line.push([x, y])
    }
    if (line.length > 1) lines.push(line)
  }
  // Ends first (one neighbour), then whatever is left (loops).
  for (let y = 0; y < ch; y++) for (let x = 0; x < cw; x++) if (m[y * cw + x] && !used.has(y * cw + x) && nbrs(x, y).length === 1) walk(x, y)
  for (let y = 0; y < ch; y++) for (let x = 0; x < cw; x++) if (m[y * cw + x] && !used.has(y * cw + x)) walk(x, y)
  if (!lines.length || !length) return null
  // Line work only: a blob thins to a short spine, and drawn as a stroke it becomes a thick worm.
  const width = area / length
  if (length < width * 3) return null
  const fmt = (v: number) => String(+v.toFixed(1))
  const lineLength = (l: [number, number][]) => l.reduce((s, p, k) => (k ? s + Math.hypot(p[0] - l[k - 1][0], p[1] - l[k - 1][1]) : 0), 0)
  const d = lines
    .filter((l) => lineLength(l) >= 8)
    .map((l) => simplify(l, 0.7))
    .filter((l) => l.length > 1)
    .map((l) => `M${l.map(([x, y]) => `${fmt(x + x0 + 0.5)} ${fmt(y + y0 + 0.5)}`).join('L')}`)
    .join('')
  return d ? { d, width: +Math.min(2.5, Math.max(0.8, width)).toFixed(1) } : null
}

/**
 * Strands regenerated over a part (schema v6), as a designer draws fur: not the image's strokes but
 * new ones in the same direction and tone.
 * - Direction: the structure tensor of the lightness (gradients squared, averaged over ~4 px); strands
 *   run across the dominant gradient. Engraved fur has one clear direction everywhere.
 * - Seeds: a jittered grid (spacing from `density`), kept where the image has a strand of this tone
 *   (lighter, or darker, than the part's median by 10).
 * - Each strand follows the direction field from its seed both ways for `length` px, inside the
 *   part, and is drawn as a lens-shaped tapered spike `width` px across at its middle.
 * All strands are one compound path (nonzero: overlaps simply fill).
 */
function synthesizeStrands(mask: Uint8Array, src: ImageData, w: number, h: number, opts: { density?: number; length?: number; width?: number; tone: 'light' | 'dark' }): string | null {
  const { density = 1.2, length = 14, width = 2.4, tone } = opts
  const { box } = measure(mask, w, h)
  const [x0, y0, x1, y1] = box
  const n = w * h
  const lum = new Float32Array(n)
  for (let p = 0; p < n; p++) lum[p] = 0.299 * src.data[p * 4] + 0.587 * src.data[p * 4 + 1] + 0.114 * src.data[p * 4 + 2]
  const sm = blurField(lum, w, h, 1)
  const gxx = new Float32Array(n), gyy = new Float32Array(n), gxy = new Float32Array(n)
  for (let y = Math.max(1, y0); y <= Math.min(h - 2, y1); y++)
    for (let x = Math.max(1, x0); x <= Math.min(w - 2, x1); x++) {
      const p = y * w + x
      const gx = (sm[p + 1] - sm[p - 1]) / 2, gy = (sm[p + w] - sm[p - w]) / 2
      gxx[p] = gx * gx
      gyy[p] = gy * gy
      gxy[p] = gx * gy
    }
  const Jxx = blurField(gxx, w, h, 4), Jyy = blurField(gyy, w, h, 4), Jxy = blurField(gxy, w, h, 4)
  const dirAt = (x: number, y: number): [number, number] => {
    const p = Math.round(y) * w + Math.round(x)
    const theta = 0.5 * Math.atan2(2 * Jxy[p], Jxx[p] - Jyy[p]) + Math.PI / 2
    return [Math.cos(theta), Math.sin(theta)]
  }
  const inside = (x: number, y: number) => x >= 0 && y >= 0 && x < w && y < h && mask[Math.round(y) * w + Math.round(x)] === 1
  const vals: number[] = []
  for (let p = 0; p < n; p++) if (mask[p]) vals.push(lum[p])
  vals.sort((a, b) => a - b)
  const median = vals[vals.length >> 1] ?? 0
  const spacing = Math.sqrt(100 / density)
  const hash = (a: number, b: number) => {
    const s = Math.sin(a * 127.1 + b * 311.7) * 43758.5453
    return s - Math.floor(s)
  }
  const fmt = (v: number) => String(+v.toFixed(1))
  const parts: string[] = []
  for (let gy = y0; gy <= y1; gy += spacing)
    for (let gx = x0; gx <= x1; gx += spacing) {
      const sx = gx + hash(gx, gy) * spacing, sy = gy + hash(gy, gx) * spacing
      if (!inside(sx, sy)) continue
      const l = sm[Math.round(sy) * w + Math.round(sx)]
      if (tone === 'light' ? l < median + 10 : l > median - 10) continue
      // Follow the field both ways from the seed, keeping a consistent heading.
      const half = (sign: number) => {
        const pts: [number, number][] = []
        let [x, y] = [sx, sy]
        let [hx, hy] = dirAt(x, y).map((v) => v * sign) as [number, number]
        for (let s = 0; s < length / 2; s += 1.5) {
          let [dx, dy] = dirAt(x, y)
          if (dx * hx + dy * hy < 0) [dx, dy] = [-dx, -dy]
          ;[hx, hy] = [dx, dy]
          const nx = x + dx * 1.5, ny = y + dy * 1.5
          if (!inside(nx, ny)) break
          ;[x, y] = [nx, ny]
          pts.push([x, y])
        }
        return pts
      }
      const line: [number, number][] = [...half(-1).reverse(), [sx, sy], ...half(1)]
      if (line.length < 4) continue
      // Lens-shaped spike: widest in the middle, pointed at both ends.
      const left: string[] = []
      const right: string[] = []
      line.forEach(([x, y], k) => {
        const a = line[Math.max(0, k - 1)], b = line[Math.min(line.length - 1, k + 1)]
        let tx = b[0] - a[0], ty = b[1] - a[1]
        const tl = Math.hypot(tx, ty) || 1
        tx /= tl
        ty /= tl
        const t = k / (line.length - 1)
        const half = (width / 2) * Math.sin(Math.PI * t)
        left.push(`${fmt(x - ty * half)} ${fmt(y + tx * half)}`)
        right.push(`${fmt(x + ty * half)} ${fmt(y - tx * half)}`)
      })
      parts.push(`M${left.join('L')}L${right.reverse().join('L')}Z`)
      if (parts.length >= 800) break
    }
  return parts.length ? parts.join('') : null
}

/** Zhang–Suen thinning, in place. */
function thin(m: Uint8Array, w: number, h: number) {
  const P = (x: number, y: number) => (x >= 0 && y >= 0 && x < w && y < h ? m[y * w + x] : 0)
  for (let changed = true; changed; ) {
    changed = false
    for (const step of [0, 1]) {
      const del: number[] = []
      for (let y = 0; y < h; y++)
        for (let x = 0; x < w; x++) {
          if (!m[y * w + x]) continue
          const p = [P(x, y - 1), P(x + 1, y - 1), P(x + 1, y), P(x + 1, y + 1), P(x, y + 1), P(x - 1, y + 1), P(x - 1, y), P(x - 1, y - 1)]
          const b = p.reduce((s, v) => s + v, 0)
          if (b < 2 || b > 6) continue
          let a = 0
          for (let k = 0; k < 8; k++) if (!p[k] && p[(k + 1) % 8]) a++
          if (a !== 1) continue
          if (step === 0 ? p[0] * p[2] * p[4] || p[2] * p[4] * p[6] : p[0] * p[2] * p[6] || p[0] * p[4] * p[6]) continue
          del.push(y * w + x)
        }
      for (const q of del) m[q] = 0
      if (del.length) changed = true
    }
  }
}

/** Douglas–Peucker. */
function simplify(pts: [number, number][], eps: number): [number, number][] {
  if (pts.length < 3) return pts
  const [ax, ay] = pts[0], [bx, by] = pts[pts.length - 1]
  const len = Math.hypot(bx - ax, by - ay) || 1
  let worst = 0, at = 0
  for (let k = 1; k < pts.length - 1; k++) {
    const dd = Math.abs((pts[k][0] - ax) * (by - ay) - (pts[k][1] - ay) * (bx - ax)) / len
    if (dd > worst) [worst, at] = [dd, k]
  }
  if (worst <= eps) return [pts[0], pts[pts.length - 1]]
  return [...simplify(pts.slice(0, at + 1), eps).slice(0, -1), ...simplify(pts.slice(at), eps)]
}

/** 4-connected pieces of `m` within `inside`. */
function piecesOf(m: Uint8Array, inside: Uint8Array, w: number): number[][] {
  const seen = new Uint8Array(m.length)
  const out: number[][] = []
  for (let s = 0; s < m.length; s++) {
    if (!m[s] || !inside[s] || seen[s]) continue
    const piece: number[] = []
    const stack = [s]
    seen[s] = 1
    while (stack.length) {
      const p = stack.pop()!
      piece.push(p)
      const x = p % w
      for (const q of [x > 0 ? p - 1 : -1, x < w - 1 ? p + 1 : -1, p - w, p + w]) if (q >= 0 && q < m.length && m[q] && inside[q] && !seen[q]) (seen[q] = 1), stack.push(q)
    }
    out.push(piece)
  }
  return out
}

/** Pixels of the mask's 4-connected pieces at least `share` of its largest piece. */
function largePieces(mask: Uint8Array, w: number, h: number, share: number): number[] {
  const seen = new Uint8Array(mask.length)
  const pieces: number[][] = []
  for (let s = 0; s < mask.length; s++) {
    if (!mask[s] || seen[s]) continue
    const piece: number[] = []
    const stack = [s]
    seen[s] = 1
    while (stack.length) {
      const p = stack.pop()!
      piece.push(p)
      const x = p % w
      for (const q of [x > 0 ? p - 1 : -1, x < w - 1 ? p + 1 : -1, p - w, p + w]) if (q >= 0 && q < mask.length && mask[q] && !seen[q]) (seen[q] = 1), stack.push(q)
    }
    pieces.push(piece)
  }
  void h
  const largest = Math.max(0, ...pieces.map((p) => p.length))
  return pieces.filter((p) => p.length >= largest * share).flat()
}

function measure(mask: Uint8Array, w: number, h: number) {
  let area = 0, x0 = w, y0 = h, x1 = -1, y1 = -1
  for (let p = 0; p < mask.length; p++) {
    if (!mask[p]) continue
    area++
    const x = p % w, y = (p - x) / w
    if (x < x0) x0 = x
    if (x > x1) x1 = x
    if (y < y0) y0 = y
    if (y > y1) y1 = y
  }
  return { area, box: [x0, y0, Math.max(x0, x1), Math.max(y0, y1)] as [number, number, number, number] }
}

/** A mask's outline smoothed: blurred (three box passes, radius ≈ sigma) and cut at one half. */
function smoothMask(m: Uint8Array, w: number, h: number, sigma: number): Uint8Array {
  return Uint8Array.from(blurField(Float32Array.from(m), w, h, sigma), (v) => (v >= 0.5 ? 1 : 0))
}

/** Three box-blur passes of radius ≈ sigma (close to a Gaussian). */
function blurField(values: Float32Array, w: number, h: number, sigma: number): Float32Array {
  const r = Math.max(1, Math.round(sigma))
  let cur = values
  for (let pass = 0; pass < 3; pass++) {
    const tmp = new Float32Array(cur.length)
    for (let y = 0; y < h; y++) {
      let s = 0
      for (let x = -r; x <= r; x++) s += x >= 0 && x < w ? cur[y * w + x] : 0
      for (let x = 0; x < w; x++) {
        tmp[y * w + x] = s / (2 * r + 1)
        const add = x + r + 1, sub = x - r
        if (add < w) s += cur[y * w + add]
        if (sub >= 0) s -= cur[y * w + sub]
      }
    }
    const out = new Float32Array(cur.length)
    for (let x = 0; x < w; x++) {
      let s = 0
      for (let y = -r; y <= r; y++) s += y >= 0 && y < h ? tmp[y * w + x] : 0
      for (let y = 0; y < h; y++) {
        out[y * w + x] = s / (2 * r + 1)
        const add = y + r + 1, sub = y - r
        if (add < h) s += tmp[add * w + x]
        if (sub >= 0) s -= tmp[sub * w + x]
      }
    }
    cur = out
  }
  return cur
}
